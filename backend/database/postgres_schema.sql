  title VARCHAR(180) NOT NULL,
  ui_component TEXT CONSTRAINT chk_template_artifact_fields_ui_component CHECK (ui_component IN ('text', 'richtext', 'textarea', 'number', 'switch', 'date', 'date_expression', 'select', 'hidden')) NOT NULL DEFAULT 'text',
  ui_group VARCHAR(180) NOT NULL DEFAULT 'general',
  is_required SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_template_artifact_fields_artifact FOREIGN KEY (template_artifact_id) REFERENCES template_artifacts(id) ON DELETE CASCADE
);
-- El unico por `data_key` hace ESTRUCTURAL lo que hoy es un `Set` llamado `seen` dentro de
