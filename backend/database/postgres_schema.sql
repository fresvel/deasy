-- LOS CAMPOS QUE EL USUARIO RELLENARA, EN LA BASE (frente 0.4, sub-paso S6 del plan maestro).
--
-- Hasta aqui vivian SOLO como fichero: `schema.json` en el prefijo de MinIO del artifact
-- (`template_artifacts.schema_object_key`). Los escribe `buildSchemaJsonFromFields`
-- (`services/admin/templates/templateLifecycle.js`) desde el multipart `schema_fields` del editor, y
-- los relee `getTemplateArtifactSchema` para el mismo formulario. NO habia tabla. Tres problemas
-- medidos, que son los mismos que el §0.8 cerro para el flujo:
--
--   1. SE COPIAN EN BINARIO AL VERSIONAR. `createTemplateArtifactVersion` y `forkDeliverableForConfig`
--      clonan el prefijo entero con `copyMinioObjectBinary`, asi que `schema.json` viaja por el MISMO
--      tubo por el que viajaba el `document_owner` que costo el frente 0 entero. Bytes copiados no se
--      auditan ni se migran con un UPDATE.
--   2. NO SE PUEDEN VALIDAR CONTRA NADA. Un `x-deasy-field-code` que diga
--      "signatures.elaborado.token" no se puede contrastar con `signature_flow_steps.slot`: uno es
--      texto dentro de un objeto JSON y el otro una columna. Con filas es un JOIN — y ese JOIN es
--      exactamente lo que el generador (S8) necesita para emitir el token de firma en el sitio
--      correcto sin que el usuario lo coloque a mano.
--   3. EL ORDEN DEPENDIA DEL ORDEN DE CLAVES DE UN OBJETO JS, y eso no es un orden. Medido
--      (experimento desechable, este commit): con la entrada
--      `anio_lectivo, 2025, responsable, 10` —el slug de `buildSchemaJsonFromFields` deja pasar los
--      enteros—, `Object.keys(properties)` devuelve `10, 2025, anio_lectivo, responsable`. JS itera
--      primero las claves de indice de array, y ademas las ORDENA numericamente entre si. O sea: la
--      corrupcion no ocurre al releer, ocurre al ESCRIBIR, y el fichero de MinIO ya sale mal. Aqui
--      `field_order` es una columna y sale del indice del array que mando el formulario.
--
-- POR QUE FILAS Y NO UNA COLUMNA `schema_json JSONB` EN `template_artifacts`. La alternativa se
-- evaluo y se descarta por escrito, para que no se reabra: cierra el problema 1 (una fila se copia
-- como fila) pero NO cierra el 2 ni el 3 —un JSONB no se puede unir a `signature_flow_steps.slot`,
-- y el orden seguiria siendo el de las claves del objeto—, que son justo los dos que el generador
-- necesita. Y hay un tercer coste, medido en el §0.6 de este mismo plan: **un CHECK no cubre una
-- columna JSONB**. Con `ui_component` como columna, los nueve componentes permitidos son una
-- restriccion de la BASE, igual que `resolver_type` en `fill_flow_steps`; dentro de un JSONB serian
-- para siempre una promesa de `SCHEMA_FIELD_COMPONENTS`, un `Set` de JavaScript.
--
-- QUE NO TIENE COLUMNA, Y POR QUE:
--   · el `type` de JSON Schema (`string`/`number`/`boolean`) es funcion PURA de `ui_component`
--     (`switch`->boolean, `number`->number, resto->string) y no tiene otro productor. Guardarlo seria
--     una segunda copia que reconciliar, que es justo el olor que el §0.8 evito. Se deriva al leer.
--   · valor por defecto, opciones de `select`, texto de ayuda y validacion NO EXISTEN HOY —ni en el
--     formulario, ni en `buildSchemaJsonFromFields`, ni en `schema.json`—. No se abre un JSONB vacio
--     a la espera: una columna sin productor ni lector es un fosil por el criterio del §0.6. Cuando
--     el editor las autore, entran por un ALTER idempotente como este.
--
-- `ON DELETE CASCADE`, a diferencia de las cabeceras de flujo, y la asimetria es del MODELO: una
-- cabecera de flujo tiene TRES portadores posibles y quedarse huerfana es un error que hay que ver,
-- mientras que un campo tiene exactamente uno y no significa nada sin su edicion (composicion).
-- Ademas conserva el comportamiento observable de `DELETE /admin/sql/template_artifacts`, que con
